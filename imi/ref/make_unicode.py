# Writes core/unicode_tables.h: the code point ranges of Unicode letters (\p{L}) and numbers (\p{N}), from Python's
# own Unicode database, for imi's word splitter.
#   python3 make_unicode.py OUT.h
import sys, unicodedata
def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(unicodedata.category(chr(cp)))
        if ok and start is None: start = cp
        if not ok and start is not None: out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out
L = ranges(lambda c: c[0] == "L")
N = ranges(lambda c: c[0] == "N")
with open(sys.argv[1], "w") as f:
    f.write(f"// Generated by ref/make_unicode.py from Unicode {unicodedata.unidata_version}: letter (L*) and number (N*) code point ranges.\n")
    f.write("#pragma once\n#include <cstdint>\n\n")
    for name, rs in (("imi_letters", L), ("imi_numbers", N)):
        f.write(f"static const uint32_t {name}[][2] = {{\n")
        for i in range(0, len(rs), 6):
            f.write("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in rs[i:i + 6]) + "\n")
        f.write("};\n")
print(len(L), "letter ranges,", len(N), "number ranges")
